#!/usr/bin/env python3
"""Packages the hooded boy's clips for the game.

    /tmp/imgenv/bin/python scripts/tools/package_hood_actor.py

Reads assets/art/prototypes/hood_clips/<clip>/ (full-canvas frames + manifest.json) and writes:

  assets/art/actors/hood_boy/<group>/<clip>/f_000.png ...   every frame cropped to its own bounding box
  scripts/actors/hood_actor_manifest.gd                      CLIPS (all the per-clip data), GROUPS, ZONES

A frame is mostly empty canvas (a 384 px square holding a boy about 120 px wide), so cropping each frame to its
silhouette (plus a 5 px margin for the fog blur) cuts the texture memory by a factor of 3-5; the crop rectangle [x, y, w, h] in canvas px is
kept in the manifest and the actor puts the cropped texture back where it was. Clips are grouped so that a zone
only loads what it uses (see ZONES); the prototype folder stays untouched.
"""
import json
import shutil
from pathlib import Path

import numpy as np
from PIL import Image

PROJECT = Path(__file__).resolve().parents[2]
SRC = PROJECT / "assets/art/prototypes/hood_clips"
DST = PROJECT / "assets/art/actors/hood_boy"
MANIFEST = PROJECT / "scripts/actors/hood_actor_manifest.gd"

PAD = 5  # the actor can blur the sprite (fog) by up to 4 px; keep room for the halo

GROUPS = {
    # The tired run and the clumsy jumps (Seedance 7549 / 7490) replace the first run, the standing / running jump sets and
    # the unused start / stop / turn clips; those stay in the prototype folder and in backups/hood-before-tired-run-jump.
    "core": ["idle_left", "scared_brake",
             "tired_start", "tired_run", "run_stop",
             "clumsy_stand_takeoff", "clumsy_stand_rise", "clumsy_stand_apex", "clumsy_stand_fall", "clumsy_stand_land",
             "clumsy_run_takeoff", "clumsy_run_rise", "clumsy_run_apex", "clumsy_run_fall", "clumsy_run_land"],
    "small": ["small_pickup", "small_hold", "small_run", "small_run_l1", "small_jump_takeoff", "small_jump_rise", "small_jump_apex",
              "small_jump_fall", "small_jump_land", "small_throw_charge", "small_throw_release", "small_throw_recover"],
    "fall": ["fall_loop", "fall_air", "fall_impact", "downed", "get_up", "flinch"],
    "grip": ["grip_engage", "grip_hold", "push", "grip_to_pull", "pull", "grip_release"],
    "fan": ["fan_pickup", "fan_swing_1", "fan_swing_2", "fan_putdown"],
    "water": ["water_plunge", "water_tread", "water_swim", "water_drown", "water_wade"],
    "shove": ["shoved_in", "shoved", "shoved_out"],
    "climb": ["climb", "grab_bridge"],
}
ZONES = {
    "level1": ["core", "small", "fall"],
    "river": ["core", "small", "fall", "grip", "fan", "water", "climb"],
    "marsh": ["core", "small", "fall", "shove", "climb"],
    "cliff": ["core", "small", "fall", "grip", "climb"],
}


def main():
    if DST.exists():
        shutil.rmtree(DST)
    DST.mkdir(parents=True)
    (DST / ".gdignore").unlink(missing_ok=True)
    clips = {}
    group_pixels = {}
    for group, names in GROUPS.items():
        for name in names:
            manifest = json.loads((SRC / name / "manifest.json").read_text())
            count = int(manifest["frames"])
            out = DST / group / name
            out.mkdir(parents=True)
            rects = []
            for i in range(count):
                image = Image.open(SRC / name / ("frame_%03d.png" % i)).convert("RGBA")
                alpha = np.array(image)[..., 3]
                ys, xs = np.where(alpha > 0)
                if len(xs) == 0:
                    box = (0, 0, 1, 1)
                else:
                    box = (max(0, int(xs.min()) - PAD), max(0, int(ys.min()) - PAD), min(image.width, int(xs.max()) + PAD + 1), min(image.height, int(ys.max()) + PAD + 1))
                image.crop(box).save(out / ("f_%03d.png" % i))
                rects.append([box[0], box[1], box[2] - box[0], box[3] - box[1]])
                group_pixels[group] = group_pixels.get(group, 0) + (box[2] - box[0]) * (box[3] - box[1])
            entry = {k: v for k, v in manifest.items() if k not in ("name", "preview", "note", "source_fps", "scale", "source_root", "source_frames", "pinned_to_ground", "mode", "upsampled")}
            entry["group"] = group
            entry["rects"] = rects
            clips[name] = entry
    text = "# Generated by scripts/tools/package_hood_actor.py. Do not edit by hand.\n"
    text += "extends RefCounted\n\n"
    text += "const ROOT_PATH := \"res://assets/art/actors/hood_boy\"\n"
    text += "const CLIPS := " + json.dumps(clips, separators=(",", ":")) + "\n"
    text += "const GROUPS := " + json.dumps(GROUPS) + "\n"
    text += "const ZONES := " + json.dumps(ZONES) + "\n\n"
    text += "static func frame_path(clip: String, index: int) -> String:\n"
    text += "\treturn \"%s/%s/%s/f_%03d.png\" % [ROOT_PATH, CLIPS[clip][\"group\"], clip, index]\n"
    MANIFEST.write_text(text)
    total = 0
    for group, pixels in group_pixels.items():
        megabytes = pixels * 4 / 1e6
        total += megabytes
        print("%-6s %5d frames  %6.1f MB as RGBA8" % (group, sum(int(clips[n]["frames"]) for n in GROUPS[group]), megabytes))
    print("all groups: %.0f MB" % total)
    for zone, groups in ZONES.items():
        print("zone %-7s %6.1f MB" % (zone, sum(group_pixels[g] * 4 / 1e6 for g in groups)))


if __name__ == "__main__":
    main()
