"""Read source alpha and record enclosed eye holes; never repaint source frames."""
import json
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage

ROOT = Path(__file__).resolve().parents[2]
manifest = (ROOT / "scripts/actors/hood_actor_manifest.gd").read_text()
clips = json.loads(manifest.split("const CLIPS := ", 1)[1].split("\nconst GROUPS", 1)[0])
tracks = json.loads((ROOT / "scripts/actors/hood_eye_tracks.gd").read_text().split("const DATA := ", 1)[1])
repairs = {}
for name, info in clips.items():
    frames = {}
    for index, track in enumerate(tracks[name]):
        if not track[3]:
            continue
        path = ROOT / f"assets/art/actors/hood_boy/{info['group']}/{name}/f_{index:03}.png"
        alpha = np.asarray(Image.open(path).convert("RGBA"))[:, :, 3]
        solid = alpha > 200
        enclosed = ndimage.binary_fill_holes(solid)
        labels, count = ndimage.label(enclosed & ~solid)
        eye = np.array(track[:2]) + info["root"] - np.array(info["rects"][index][:2])
        mask = np.zeros_like(solid)
        for label in range(1, count + 1):
            yy, xx = np.where(labels == label)
            if len(xx) <= 500 and np.linalg.norm(np.array([xx.mean(), yy.mean()]) - eye) < 24:
                mask |= labels == label
        # Include the feathered interior rim without expanding the silhouette.
        mask = ndimage.binary_dilation(mask, iterations=1) & enclosed
        spans = []
        for y in np.flatnonzero(mask.any(axis=1)):
            xs = np.flatnonzero(mask[y])
            for run in np.split(xs, np.flatnonzero(np.diff(xs) > 1) + 1):
                spans.append([int(y), int(run[0]), int(run[-1]) + 1])
        if spans:
            frames[str(index)] = spans
    if frames:
        repairs[name] = frames
    print(name, len(frames), "frames with enclosed eye holes")
(ROOT / "scripts/actors/hood_eye_repairs.gd").write_text(
    "# Generated by build_hood_eye_repairs.py; enclosed source-alpha repairs only.\nextends RefCounted\nconst DATA := "
    + json.dumps(repairs, separators=(",", ":")) + "\n"
)
