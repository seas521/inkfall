#!/usr/bin/env python3
"""Writes scripts/actors/hood_actor_soles.gd: for every packaged frame, the points of the visible sole (texture pixels).

    /tmp/imgenv/bin/python scripts/tools/build_hood_soles.py        (after package_hood_actor.py)

The C zone's foot-to-surface correction needs them for every frame he shows. Reading them off the textures while playing
(Texture2D.get_image on a VRAM-compressed texture reads it back from the GPU) stalls the first time each frame is shown:
a hitch the first time an animation plays. Computed here instead, once, with the same rule: the lowest opaque pixel of
every third column, within 12 rows of the bottom of the silhouette.
"""
import json
import re
from pathlib import Path

import numpy as np
from PIL import Image

PROJECT = Path(__file__).resolve().parents[2]
MANIFEST = (PROJECT / "scripts/actors/hood_actor_manifest.gd").read_text()
clips = json.loads([l for l in MANIFEST.splitlines() if l.startswith("const CLIPS")][0].split(":=", 1)[1])

lines = ["# Generated by scripts/tools/build_hood_soles.py: the visible sole of every frame, as x, y pairs in texture pixels.",
         "extends RefCounted", "", "const SOLES := {"]
total = 0
for name, data in clips.items():
    frames = []
    for index in range(int(data["frames"])):
        path = PROJECT / f"assets/art/actors/hood_boy/{data['group']}/{name}/f_{index:03d}.png"
        alpha = np.array(Image.open(path).convert("RGBA"))[..., 3].astype(float) / 255.0
        ys, xs = np.where(alpha > 0.0)
        points = []
        if len(xs):
            x0, x1 = xs.min(), xs.max() + 1
            top, bottom = ys.min(), ys.max()
            for x in range(x0, x1, 3):
                for y in range(bottom, max(top, bottom - 12) - 1, -1):
                    if alpha[y, x] > 0.6:
                        points += [x + 0.5, y + 1.0]
                        break
        total += len(points) // 2
        frames.append("[" + ",".join(f"{v:g}" for v in points) + "]")
    lines.append(f'\t"{name}": [' + ",".join(frames) + "],")
lines.append("}")
(PROJECT / "scripts/actors/hood_actor_soles.gd").write_text("\n".join(lines) + "\n")
print("wrote", total, "sole points for", len(clips), "clips")
